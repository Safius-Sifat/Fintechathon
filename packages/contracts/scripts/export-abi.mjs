// Exports compiled ABIs to packages/contracts/abi/*.json and packages/schema/src/generated/abi.ts.
// Run after `forge build`. With --check, fails if committed ABIs differ from the compiled source.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const CONTRACTS = ["MandateWallet", "WalletFactory", "DemoUSD", "DemoVault", "EvidenceAnchor"];
const check = process.argv.includes("--check");
const abis = Object.fromEntries(
  CONTRACTS.map((name) => [name, JSON.parse(readFileSync(resolve(root, `out/${name}.sol/${name}.json`), "utf8")).abi]),
);
const files = {};
for (const [name, abi] of Object.entries(abis)) files[resolve(root, `abi/${name}.json`)] = JSON.stringify(abi, null, 2) + "\n";
const camel = (n) => n[0].toLowerCase() + n.slice(1);
files[resolve(root, "../schema/src/generated/abi.ts")] =
  "// Generated by packages/contracts/scripts/export-abi.mjs from compiled source. Do not edit.\n" +
  Object.entries(abis).map(([n, abi]) => `export const ${camel(n)}Abi = ${JSON.stringify(abi)} as const;\n`).join("");
let stale = [];
for (const [path, content] of Object.entries(files)) {
  if (check) {
    let current = null;
    try { current = readFileSync(path, "utf8"); } catch {}
    if (current !== content) stale.push(path);
  } else {
    mkdirSync(resolve(path, ".."), { recursive: true });
    writeFileSync(path, content);
  }
}
if (stale.length) {
  console.error(`ABI out of date; run: pnpm --filter @mandate/contracts abi\n${stale.join("\n")}`);
  process.exit(1);
}
console.log(check ? "ABIs match compiled source" : "ABIs exported");
